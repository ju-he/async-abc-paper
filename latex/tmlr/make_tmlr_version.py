def replace_once(text: str, old: str, new: str, what: str) -> str:
    n = text.count(old)
    if n != 1:
        raise SystemExit(f"{what}: expected exactly one occurrence of {old!r}, found {n}")
    return text.replace(old, new)


def sub_once(text: str, pattern: str, repl: str, what: str, flags: int = re.M) -> str:
    text, n = re.subn(pattern, repl, text, flags=flags)
    if n != 1:
        raise SystemExit(f"{what}: expected exactly one match of /{pattern}/, found {n}")
    return text


def main() -> None:
    src = SOURCE.read_text(encoding="utf-8")

    pre, body = src.split(r"\begin{document}", 1)
    body, tail = body.rsplit(r"\end{document}", 1)
    if tail.strip():
        raise SystemExit(f"unexpected text after \\end{{document}}: {tail.strip()[:80]!r}")

    # --- macros and theorem environments defined in the Springer preamble carry over
    carried = [
        line for line in pre.splitlines()
        if re.match(r"\\(newcommand|renewcommand|providecommand|newtheorem|theoremstyle|DeclareMathOperator)\b", line)
    ]
    if not any("newtheorem" in line for line in carried):
        raise SystemExit("no \\newtheorem lines found in the Springer preamble")

    # --- title, authors, abstract, keywords, \maketitle come out of the body
    m = re.search(r"^\\title\[[^\]]*\]\{(.+)\}[ \t]*$", body, re.M)
    if m is None:
        raise SystemExit("could not find \\title[short]{long} in the source")
    title = m.group(1)
    body = body[: m.start()] + body[m.end():]

    body, n_auth = re.subn(r"^\\(author|affil)\*?\[.*$\n?", "", body, flags=re.M)
    if n_auth < 1:
        raise SystemExit("no \\author/\\affil lines found")

    m = re.search(r"^\\abstract\{(.*)\}[ \t]*$", body, re.M)
    if m is None:
        raise SystemExit("could not find the one-line \\abstract{...}")
    abstract = m.group(1)
    body = body[: m.start()] + body[m.end():]

    body = sub_once(body, r"^\\keywords\{.*\}[ \t]*$\n?", "", "keywords")
    body = sub_once(body, r"^\\maketitle[ \t]*$\n?", "", "maketitle")

    # --- citations: natbib author-year
    body, n_cites = re.subn(r"\\cite(?=[\[{])", r"\\citep", body)
    for old, new in CITATION_FIXES:
        body = replace_once(body, old, new, "citation fix")

    # --- tables
    body, n_botrule = re.subn(r"\\botrule\b", r"\\bottomrule", body)
    if n_botrule < 1:
        raise SystemExit("no \\botrule found; has the table format changed?")

    # --- back matter: Springer acknowledgments + declarations -> TMLR sections,
    #     bibliography before the appendix, \appendix instead of the appendices env
    i = body.index(replace_once(body, r"\bmhead{Acknowledgments}", r"\bmhead{Acknowledgments}", "bmhead") and r"\bmhead{Acknowledgments}")
    j = body.index(replace_once(body, r"\begin{appendices}", r"\begin{appendices}", "appendices") and r"\begin{appendices}")
    if not i < j:
        raise SystemExit("acknowledgments must precede the appendices")
    body = body[:i] + BACK_MATTER + body[j + len(r"\begin{appendices}"):]
    body = replace_once(body, "\\end{appendices}\n", "", "end appendices")
    body = replace_once(body, "\\bibliography{sn-bibliography}\n", "", "springer bibliography")

    for old, new in TEXT_FIXES:
        body = replace_once(body, old, new, "text fix")
    for old, new in TMLR_ONLY:
        body = replace_once(body, old, new, "TMLR-only framing")

    leftovers = sorted(set(re.findall(r"\\(?:bmhead|botrule|fnm|sur|affil|orgname|orgdiv|keywords|backmatter)\b", body)))
    if leftovers:
        raise SystemExit(f"sn-jnl macros left in the body: {leftovers}")

    out = (
        PREAMBLE_HEAD
        + "\n"
        + "\n".join(carried)
        + "\n\n"
        + "\\title{" + title + "}\n\n"
        + AUTHOR_BLOCK
        + "\n\\begin{document}\n\n\\maketitle\n\n"
        + "\\begin{abstract}\n" + abstract + "\n\\end{abstract}\n\n"
        + body.strip("\n")
        + "\n\n\\end{document}\n"
    )
    out = re.sub(r"\n{3,}", "\n\n", out)
    TARGET.write_text(out, encoding="utf-8")
    print(
        f"wrote {TARGET.name}: {len(out.splitlines())} lines; "
        f"{n_cites} \\cite -> \\citep ({len(CITATION_FIXES)} textual fixes), "
        f"{n_botrule} \\botrule -> \\bottomrule, {n_auth} author/affil lines dropped, "
        f"{len(carried)} preamble macro lines carried over"
    )


if __name__ == "__main__":
    main()
