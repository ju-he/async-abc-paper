"""Derive the TMLR submission (tmlr-article.tex) from the Springer source.

Source: ../sn-article-template/sn-article.tex (the sn-jnl version, single
source of truth for the prose, figures, tables and bibliography).

What changes: the sn-jnl scaffolding (class, title/author/abstract/keywords
macros, \botrule, the appendices environment, the Springer back matter) is
replaced by the TMLR one; \cite becomes natbib author-year (\citep, with the
handful of textual uses turned into \citet/\citealp/\citealt); the
bibliography moves before the appendix as in the TMLR template; a Broader
Impact Statement and a Reproducibility paragraph replace the Springer
declarations; "our fork" of Propulate becomes "a fork" for double-blind
review; and TMLR_ONLY adds the framing sentences for TMLR's audience (the
simulation-based-inference umbrella, sequential neural SBI and synchronous
SGD as fellow barrier-payers, the baseline-class scoping). Nothing else in
the prose is touched.

Every targeted rewrite asserts that its anchor occurs exactly once in the
source, so an edit to the Springer file that moves or removes an anchor
fails this script instead of silently producing a wrong TMLR version.

Usage: python3 make_tmlr_version.py   (writes tmlr-article.tex next to it)
"""
